test('blind studies conceal source labels and scores, reject duplicate briefs, and accept one complete ballot per invitation', async () => {
  const snapshot = fixture();
  snapshot.benchmark = await benchmarkFestival(snapshot, { propose: async () => ({ selectedIds: ['b', 'c'] }) });
  const sourceId = store.save(snapshot);
  const study = createStudy({ sourceIds: [sourceId], reviewers: ['Test promoter'] });
  assert.ok(!store.examples().some(example => example.id === sourceId), 'retaining a blind study must not publish its source');
  const [studyId, token] = study.invitations[0].url.split('#')[1].split(':');
  const blind = blindReview(studyId, token);
  assert.equal(blind.cases.length, 1);
  for (const key of ['sourceId', 'qloo', 'control', 'score', 'receipt']) assert.ok(!Object.hasOwn(blind.cases[0], key));
  assert.equal(studyReport(studyId).completedReviewers, 0);
  assert.throws(() => createStudy({ sourceIds: [sourceId, sourceId], reviewers: ['Test'] }), /independent/);
  assert.throws(() => blindReview(studyId, 'wrong'), /not found/);
  assert.throws(() => submitBallot(studyId, token, { judgments: [] }), /one judgment/);
  const ballot = { judgments: [{ caseId: blind.cases[0].caseId, preference: 'a', reason: 'Test fixture preference only; not a real promoter evaluation.' }] };
  assert.equal((await fetch(`${base}/api/studies/${studyId}`)).status, 401);
  assert.equal((await fetch(`${base}/api/reviews/${studyId}`)).status, 404);
  const page = await fetch(`${base}/api/reviews/${studyId}`, { headers: { 'x-review-token': token } });
  assert.equal(page.status, 200);
  const response = await fetch(`${base}/api/reviews/${studyId}/ballot`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-review-token': token }, body: JSON.stringify(ballot) });
  assert.equal(response.status, 200);
  assert.equal((await response.json()).submitted, true);
  assert.throws(() => submitBallot(studyId, token, ballot), /already/);
  assert.equal(studyReport(studyId).completedReviewers, 1);
  assert.match(studyReport(studyId).conclusion, /not a causal/);
});
