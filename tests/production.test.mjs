const directory = mkdtempSync(join(tmpdir(), 'houselights-production-'));
process.env.DATA_DIR = directory; process.env.PUBLIC_DEMO = '1'; process.env.ORGANIZER_TOKEN = 'test-only-credential-'.repeat(3);
