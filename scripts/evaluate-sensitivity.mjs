// How robust are the published findings to two arbitrary choices?
//  1. The near-tie band (0.002): re-run tie detection at 0.001, 0.002 and 0.005.
//  2. The illustrative fees: perturb every fee by ±20% (200 seeded draws per brief) and ask
//     whether withdrawing Qloo evidence still changes the decision — the same class:all
//     ablation of buildDecisionProof that produces the published "7 of 9".
// Uses the 9 briefs with a complete Qloo ranking. Seeded; no provider calls.
// Writes results/sensitivity.{json,md}.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const repo = resolve(import.meta.dirname, '..');
const { runAutopilot } = await import('../server/autopilot.mjs');
const { rankComparability, tieSensitivity } = await import('../server/affinity.mjs');
const { buildDecisionProof } = await import('../server/decision-proof.mjs');
const cases = JSON.parse(readFileSync(join(repo, 'deploy', 'judge-cases.json'), 'utf8')).cases;
const BANDS = [0.001, 0.002, 0.005], DRAWS = 200, NOISE = 0.2;
let seed = 23; const rnd = () => ((seed = Math.imul(seed ^ seed >>> 15, 2246822507) + 0x9e3779b9 | 0) >>> 0) / 2 ** 32;
const withdrawalChanges = (items, constraints, receipts) => buildDecisionProof({ memo: { items, constraints }, receipts }).ablations.find(row => row.id === 'class:all')?.changed ?? null;

const rows = [];
for (const record of cases) {
  const source = record.snapshot;
  if (!rankComparability(source.memo.items).comparable) continue;
  const result = await runAutopilot({ ...source, memo: { ...source.memo, exampleBookingTerms: true } }, {});
  if (result.strategies.status !== 'feasible') continue;
  const items = result.items, constraints = result.constraints, receipts = source.receipts;
  const bands = Object.fromEntries(BANDS.map(band => { const t = tieSensitivity(items, constraints, band); return [band, { pairs: t.groups.length, restsOnNearTie: t.restsOnNearTie }]; }));
  const published = withdrawalChanges(items, constraints, receipts);
  let changed = 0, evaluated = 0;
  for (let draw = 0; draw < DRAWS; draw++) {
    const noisy = items.map(item => ({ ...item, terms: { ...item.terms, fee: Number.isFinite(item.terms?.fee) ? Math.round(item.terms.fee * (1 - NOISE + 2 * NOISE * rnd())) : item.terms?.fee } }));
    const value = withdrawalChanges(noisy, constraints, receipts); if (value == null) continue;
    evaluated++; if (value) changed++;
  }
  rows.push({ brief: record.title, publishedWithdrawalChanges: published, feeNoise: { draws: evaluated, withdrawalChanges: changed, share: evaluated ? changed / evaluated : null }, bands });
}
const robust = rows.filter(row => row.feeNoise.share >= 0.95).length, never = rows.filter(row => row.feeNoise.share <= 0.05).length;
const totals = { briefs: rows.length, publishedChanged: rows.filter(row => row.publishedWithdrawalChanges).length, robustUnderNoise: robust, neverUnderNoise: never, mixed: rows.length - robust - never,
  meanShare: rows.reduce((sum, row) => sum + (row.feeNoise.share ?? 0), 0) / Math.max(1, rows.length),
  nearTieDecides: Object.fromEntries(BANDS.map(band => [band, rows.filter(row => row.bands[band].restsOnNearTie).length])),
  nearTiePairs: Object.fromEntries(BANDS.map(band => [band, rows.reduce((sum, row) => sum + row.bands[band].pairs, 0)])) };
const pct = value => value == null ? '—' : `${Math.round(value * 100)}%`;
writeFileSync(join(repo, 'results', 'sensitivity.json'), JSON.stringify({ version: '1.0', seed: 23, draws: DRAWS, feeNoise: NOISE, bands: BANDS, providerCalls: 0, rows, totals }, null, 2) + '\n');
writeFileSync(join(repo, 'results', 'sensitivity.md'), `# Sensitivity of the published findings

Generated by \`node scripts/evaluate-sensitivity.mjs\` (seed 23, no provider calls). It covers the ${rows.length} feasible briefs with a complete Qloo ranking.

## Fee noise: does withdrawing Qloo evidence still change the decision?

Every illustrative fee is multiplied by a random factor in [0.8, 1.2], with ${DRAWS} draws per brief. The question is the one behind the published "${totals.publishedChanged} of ${rows.length}": the same \`class:all\` evidence-withdrawal ablation.

| Brief | Published | Changes under ±20% fee noise |
|---|---|---|
${rows.map(row => `| ${row.brief} | ${row.publishedWithdrawalChanges ? 'changes' : 'no change'} | ${row.feeNoise.withdrawalChanges}/${row.feeNoise.draws} (${pct(row.feeNoise.share)}) |`).join('\n')}

- **Robust** (changes in at least 95% of draws): ${robust} of ${rows.length} briefs.
- **Never changes** (5% of draws or fewer): ${never}.
- **Mixed** (depends on the fees): ${totals.mixed}.
- Mean share of draws where withdrawal changes the decision: ${pct(totals.meanShare)}.

Withdrawing Qloo evidence influences the decision. This measures influence, not ticket sales, and the fees remain illustrative.

## Near-tie band

| Band | Near-tie pairs (all briefs) | Briefs where a near-tie decides the bill |
|---|---|---|
${BANDS.map(band => `| ${band} | ${totals.nearTiePairs[band]} | ${totals.nearTieDecides[band]} |`).join('\n')}

0.002 is the declared band. Qloo publishes no margin of error, so the band is a Houselights choice. The table shows how many decisions a different choice would put in the promoter's hands.
`);
