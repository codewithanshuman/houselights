// Does the exact optimizer choose differently from simply booking the top-k acts by Qloo
// rank? Seeded scenarios on every brief whose Qloo ranking is complete: each scenario
// perturbs fees (×0.80–1.25), drops availability (10% per act) and sets the budget at
// 70–150% of the top-k cost. Writes results/rank-vs-optimum.{json,md}. No provider calls.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
const repo = resolve(import.meta.dirname, '..');
const { optimizeSlate } = await import('../server/optimizer.mjs');
const { withAffinityFit, rankComparability } = await import('../server/affinity.mjs');
const { runAutopilot } = await import('../server/autopilot.mjs');
const cases = JSON.parse(readFileSync(join(repo, 'deploy', 'judge-cases.json'), 'utf8')).cases;
const N = 400; let seed = 11;
const rnd = () => ((seed = Math.imul(seed ^ seed >>> 15, 2246822507) + 0x9e3779b9 | 0) >>> 0) / 2 ** 32;
const rows = [];
for (const c of cases) {
  const s = c.snapshot;
  if (!rankComparability(s.memo.items).comparable) continue;
  const base = (await runAutopilot({ ...s, memo: { ...s.memo, exampleBookingTerms: true } }, {})).items;
  const affinity = withAffinityFit(base, s.receipts); if (affinity.basis !== 'qloo-affinity') continue;
  const ranked = base.filter(item => item.evidence?.rank && Number.isFinite(item.rank)).sort((a, b) => a.rank - b.rank);
  // Ordinal fit is the 1.0 rank-position formula, 1 − (rank − 1)/(n − 1); affinity fit is
  // the current fixed-span scaling of Qloo's scores. Autopilot items already carry affinity fit.
  const n = ranked.length, ordinalFit = item => item.evidence?.rank && Number.isFinite(item.rank) ? (n > 1 ? 1 - (ranked.indexOf(item)) / (n - 1) : 1) : item.fit;
  const k = s.memo.constraints.slots, fits = { ordinal: new Map(base.map(i => [i.id, ordinalFit(i)])), affinity: new Map(affinity.items.map(i => [i.id, i.fit])) };
  const row = { brief: c.title, scenarios: 0, topKFeasible: 0, differsOrdinal: 0, differsAffinity: 0, topKInfeasible: 0, optimizerFoundAlternative: 0, noFeasibleLineup: 0 };
  for (let t = 0; t < N; t++) {
    const terms = new Map(base.map(i => [i.id, { ...i.terms, fee: i.terms.fee == null ? null : Math.round(i.terms.fee * (0.8 + 0.45 * rnd())), available: i.terms.available && rnd() > 0.1 }]));
    const top = ranked.slice(0, k), topCost = top.reduce((sum, i) => sum + (terms.get(i.id).fee ?? Infinity), 0);
    const constraints = { ...s.memo.constraints, budget: Math.round((Number.isFinite(topCost) ? topCost : s.memo.constraints.budget) * (0.7 + 0.8 * rnd())), lockedIds: [], excludedIds: [] };
    row.scenarios++;
    const pool = name => base.map(i => ({ ...i, fit: fits[name].get(i.id), terms: terms.get(i.id) }));
    const topIds = top.map(i => i.id).sort().join();
    const topFeasible = optimizeSlate(pool('affinity'), { ...constraints, lockedIds: top.map(i => i.id) }).selectedIds?.length === k;
    if (topFeasible) {
      row.topKFeasible++;
      for (const name of ['ordinal', 'affinity']) if ([...(optimizeSlate(pool(name), constraints).selectedIds ?? [])].sort().join() !== topIds) row[name === 'ordinal' ? 'differsOrdinal' : 'differsAffinity']++;
    } else {
      row.topKInfeasible++;
      if (optimizeSlate(pool('affinity'), constraints).selectedIds?.length === k) row.optimizerFoundAlternative++; else row.noFeasibleLineup++;
    }
  }
  rows.push(row);
}
const sum = key => rows.reduce((total, row) => total + row[key], 0);
const totals = Object.fromEntries(['scenarios', 'topKFeasible', 'differsOrdinal', 'differsAffinity', 'topKInfeasible', 'optimizerFoundAlternative', 'noFeasibleLineup'].map(key => [key, sum(key)]));
const pct = (a, b) => b ? `${(100 * a / b).toFixed(1)}%` : '—';
writeFileSync(join(repo, 'results', 'rank-vs-optimum.json'), JSON.stringify({ version: '1.0', seed: 11, scenariosPerBrief: N, providerCalls: 0, rows, totals }, null, 2) + '\n');
writeFileSync(join(repo, 'results', 'rank-vs-optimum.md'), `# Optimizer vs booking the top-k by Qloo rank

Generated by \`node scripts/evaluate-rank-vs-optimum.mjs\` (seed 11, ${N} scenarios per brief, no provider calls). Each scenario perturbs fees (×0.80–1.25), makes each act unavailable with probability 0.10, and sets the budget at 70–150% of the top-k cost. Only the ${rows.length} briefs with a complete Qloo ranking and affinity scores are used.

| Brief | Scenarios | Top-k feasible | Optimum ≠ top-k (affinity / ordinal) | Top-k infeasible | Optimizer found a bookable alternative | No feasible lineup |
|---|---|---|---|---|---|---|
${rows.map(r => `| ${r.brief} | ${r.scenarios} | ${r.topKFeasible} | ${r.differsAffinity} / ${r.differsOrdinal} | ${r.topKInfeasible} | ${r.optimizerFoundAlternative} | ${r.noFeasibleLineup} |`).join('\n')}
| **Total** | ${totals.scenarios} | ${totals.topKFeasible} | **${totals.differsAffinity} / ${totals.differsOrdinal}** | ${totals.topKInfeasible} | ${totals.optimizerFoundAlternative} | ${totals.noFeasibleLineup} |

**Finding 1: re-ranking is rare and comes from near-ties.** Where the top-k acts by Qloo rank are bookable, the optimizer chooses differently in ${totals.differsAffinity} of ${totals.topKFeasible} scenarios (${pct(totals.differsAffinity, totals.topKFeasible)}) under affinity fit, against ${totals.differsOrdinal} (${pct(totals.differsOrdinal, totals.topKFeasible)}) under ordinal fit. Every difference comes from briefs where Qloo's scores are nearly tied: ${rows.filter(row => row.differsAffinity).map(row => row.brief.split(':')[0]).join(', ') || 'none'}. In New York, Sault (rank 2, affinity 0.9580) and Jordan Rakei (rank 3, 0.9579) are 0.0001 apart. Margin-aware fit lets Rakei's local and audience-comparison evidence and lower fee decide. Ordinal fit treats rank 2 vs 3 as a 0.5 fit gap. Elsewhere fit dominates the declared policy, and the optimizer books Qloo's top-k.

**Finding 2: the main contribution is constraint handling.**

In ${totals.topKInfeasible} of ${totals.scenarios} scenarios (${pct(totals.topKInfeasible, totals.scenarios)}) the top-k by rank could not be booked under the budget, fees, availability or genre rules:
- in ${totals.optimizerFoundAlternative} of them the optimizer found the best bookable lineup;
- in the other ${totals.noFeasibleLineup} it reported that no lineup satisfies the constraints instead of inventing one.

The pitch is therefore *constraint-correct, auditable booking decisions with Qloo receipts*, not "better than Qloo's ranking". This result does not measure ticket sales or decision quality. Fees and availability are illustrative.
`);
